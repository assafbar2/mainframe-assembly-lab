/**
 * EBCDIC (IBM Code Page 037) <-> ASCII Translation Tables & Utilities
 * The standard character set of IBM Mainframes since 1964.
 */

// Mapping from ASCII byte (0-255) to EBCDIC byte
export const ASCII_TO_EBCDIC = new Uint8Array(256);

// Mapping from EBCDIC byte (0-255) to ASCII byte
export const EBCDIC_TO_ASCII = new Uint8Array(256);

// Standard IBM Code Page 037 Table
const CP037_TABLE: [number, number][] = [
  // Control characters
  [0x00, 0x00], [0x01, 0x01], [0x02, 0x02], [0x03, 0x03],
  [0x09, 0x05], [0x0A, 0x25], [0x0D, 0x0D], [0x1B, 0x27],
  // Space and Punctuation
  [0x20, 0x40], // Space -> 0x40 (Famous Mainframe Space byte!)
  [0x21, 0x5A], // !
  [0x22, 0x7F], // "
  [0x23, 0x7B], // #
  [0x24, 0x5B], // $
  [0x25, 0x6C], // %
  [0x26, 0x50], // &
  [0x27, 0x7D], // '
  [0x28, 0x4D], // (
  [0x29, 0x5D], // )
  [0x2A, 0x5C], // *
  [0x2B, 0x4E], // +
  [0x2C, 0x6B], // ,
  [0x2D, 0x60], // -
  [0x2E, 0x4B], // .
  [0x2F, 0x61], // /
  // Digits: 0-9 in EBCDIC are 0xF0 - 0xF9
  [0x30, 0xF0], [0x31, 0xF1], [0x32, 0xF2], [0x33, 0xF3], [0x34, 0xF4],
  [0x35, 0xF5], [0x36, 0xF6], [0x37, 0xF7], [0x38, 0xF8], [0x39, 0xF9],
  // Symbols
  [0x3A, 0x7A], // :
  [0x3B, 0x5E], // ;
  [0x3C, 0x4C], // <
  [0x3D, 0x7E], // =
  [0x3E, 0x6E], // >
  [0x3F, 0x6F], // ?
  [0x40, 0x7C], // @
  // Uppercase Letters: Non-contiguous blocks in EBCDIC!
  // A-I: 0xC1 - 0xC9
  [0x41, 0xC1], [0x42, 0xC2], [0x43, 0xC3], [0x44, 0xC4], [0x45, 0xC5],
  [0x46, 0xC6], [0x47, 0xC7], [0x48, 0xC8], [0x49, 0xC9],
  // J-R: 0xD1 - 0xD9
  [0x4A, 0xD1], [0x4B, 0xD2], [0x4C, 0xD3], [0x4D, 0xD4], [0x4E, 0xD5],
  [0x4F, 0xD6], [0x50, 0xD7], [0x51, 0xD8], [0x52, 0xD9],
  // S-Z: 0xE2 - 0xE9
  [0x53, 0xE2], [0x54, 0xE3], [0x55, 0xE4], [0x56, 0xE5], [0x57, 0xE6],
  [0x58, 0xE7], [0x59, 0xE8], [0x5A, 0xE9],
  // Brackets
  [0x5B, 0xBA], // [
  [0x5C, 0xE0], // \
  [0x5D, 0xBB], // ]
  [0x5E, 0xB0], // ^
  [0x5F, 0x6D], // _
  // Lowercase Letters: Also non-contiguous!
  // a-i: 0x81 - 0x89
  [0x61, 0x81], [0x62, 0x82], [0x63, 0x83], [0x64, 0x84], [0x65, 0x85],
  [0x66, 0x86], [0x67, 0x87], [0x68, 0x88], [0x69, 0x89],
  // j-r: 0x91 - 0x99
  [0x6A, 0x91], [0x6B, 0x92], [0x6C, 0x93], [0x6D, 0x94], [0x6E, 0x95],
  [0x6F, 0x96], [0x70, 0x97], [0x71, 0x98], [0x72, 0x99],
  // s-z: 0xA2 - 0xA9
  [0x73, 0xA2], [0x74, 0xA3], [0x75, 0xA4], [0x76, 0xA5], [0x77, 0xA6],
  [0x78, 0xA7], [0x79, 0xA8], [0x7A, 0xA9],
  // Braces
  [0x7B, 0xC0], // {
  [0x7C, 0x4F], // |
  [0x7D, 0xD0], // }
  [0x7E, 0xA1], // ~
];

// Initialize default mapping
for (let i = 0; i < 256; i++) {
  ASCII_TO_EBCDIC[i] = 0x40; // Default unknown to EBCDIC space
  EBCDIC_TO_ASCII[i] = 0x2E; // Default unknown to '.'
}

for (const [ascii, ebcdic] of CP037_TABLE) {
  ASCII_TO_EBCDIC[ascii] = ebcdic;
  EBCDIC_TO_ASCII[ebcdic] = ascii;
}

/**
 * Converts an ASCII string to an EBCDIC byte array
 */
export function asciiToEbcdic(str: string): Uint8Array {
  const bytes = new Uint8Array(str.length);
  for (let i = 0; i < str.length; i++) {
    const code = str.charCodeAt(i) & 0xff;
    bytes[i] = ASCII_TO_EBCDIC[code] ?? 0x40;
  }
  return bytes;
}

/**
 * Converts an EBCDIC byte array to an ASCII string
 */
export function ebcdicToAscii(bytes: Uint8Array): string {
  let res = '';
  for (let i = 0; i < bytes.length; i++) {
    const ascii = EBCDIC_TO_ASCII[bytes[i]] ?? 0x2e;
    // Keep printable or space
    if (ascii >= 32 && ascii <= 126) {
      res += String.fromCharCode(ascii);
    } else {
      res += '.';
    }
  }
  return res;
}

/**
 * Converts a single EBCDIC byte to a single character printable representation
 */
export function ebcdicByteToChar(byte: number): string {
  const ascii = EBCDIC_TO_ASCII[byte & 0xff];
  if (ascii >= 32 && ascii <= 126) {
    return String.fromCharCode(ascii);
  }
  return '·';
}
